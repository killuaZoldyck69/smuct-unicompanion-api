function toUtcDate(dateStr: string): Date {
  const match = dateStr.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (match) {
    const year = parseInt(match[1], 10);
    const month = parseInt(match[2], 10);
    const day = parseInt(match[3], 10);
    return new Date(Date.UTC(year, month - 1, day));
  }
  return new Date(dateStr);
}

async function seedAcademicCalendar() {
  console.log("🌱 Starting Academic Calendar Seed Process...");

  try {
    // Check if Winter 2026 already exists
    const existing = await prisma.academicCalendar.findFirst({
      where: {
        semester: "Winter 2026",
      },
    });

    if (existing) {
      console.log(`ℹ️ Academic Calendar for "Winter 2026" found (ID: ${existing.id}). Refreshing events...`);

      // Update calendar metadata
      await prisma.academicCalendar.update({
        where: { id: existing.id },
        data: {
          title: "ACADEMIC CALENDAR - WINTER SEMESTER 2026",
          academicYear: 2026,
          status: "PUBLISHED",
          isActive: true,
          isGlobal: true, // Global so all students can view
          targetFaculties: [
            "Faculty of Design & Technology",
            "Faculty of Engineering & Technology",
            "Faculty of Fine & Performing Arts",
            "Faculty of Humanities & Social Sciences",
            "Faculty of Management & General Studies",
          ],
          publishedAt: new Date(),
        },
      });

      // Clear old events and re-populate
      await prisma.calendarEvent.deleteMany({
        where: { calendarId: existing.id },
      });

      await prisma.calendarEvent.createMany({
        data: WINTER_2026_EVENTS.map((ev) => ({
          calendarId: existing.id,
          title: ev.title,
          description: ev.description,
          category: ev.category,
          startDate: toUtcDate(ev.startDate),
          endDate: ev.endDate ? toUtcDate(ev.endDate) : null,
          weekNumber: ev.weekNumber,
          isHoliday: ev.isHoliday,
          isAllDay: ev.isAllDay,
          remarks: ev.remarks,
        })),
      });

      console.log(`✅ Successfully updated Winter 2026 calendar with ${WINTER_2026_EVENTS.length} events!`);
    } else {
      console.log("Creating new Academic Calendar for Winter 2026...");

      const created = await prisma.academicCalendar.create({
        data: {
          title: "ACADEMIC CALENDAR - WINTER SEMESTER 2026",
          semester: "Winter 2026",
          academicYear: 2026,
          status: "PUBLISHED",
          isActive: true,
          isGlobal: true,
          targetFaculties: [
            "Faculty of Design & Technology",
            "Faculty of Engineering & Technology",
            "Faculty of Fine & Performing Arts",
            "Faculty of Humanities & Social Sciences",
            "Faculty of Management & General Studies",
          ],
          publishedAt: new Date(),
          events: {
            create: WINTER_2026_EVENTS.map((ev) => ({
              title: ev.title,
              description: ev.description,
              category: ev.category,
              startDate: toUtcDate(ev.startDate),
              endDate: ev.endDate ? toUtcDate(ev.endDate) : null,
              weekNumber: ev.weekNumber,
              isHoliday: ev.isHoliday,
              isAllDay: ev.isAllDay,
              remarks: ev.remarks,
            })),
          },
        },
      });

      console.log(`✅ Successfully created and published Academic Calendar (ID: ${created.id}) with ${WINTER_2026_EVENTS.length} events!`);
    }
  } catch (error) {
    console.error("❌ Failed to seed academic calendar:", error);
  } finally {
    await prisma.$disconnect();
  }
}

seedAcademicCalendar();
